export function getPhoneBySlug(slug) {
  return PHONES.find((p) => p.slug === slug) || PHONES[0];
}

export function getPhonesByBrand(brandSlug) {
  if (!brandSlug) return PHONES;
  return PHONES.filter((p) => p.brand === brandSlug);
}

export function getRelatedPhones(currentSlug, limit = 4) {
  const current = getPhoneBySlug(currentSlug);
  return PHONES.filter((p) => p.slug !== currentSlug && p.brand === current.brand).slice(0, limit);
}
